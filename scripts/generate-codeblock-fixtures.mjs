#!/usr/bin/env node
import { promises as fs } from "fs";
import path from "path";
import { getSingletonHighlighter } from "shiki";
import { unified } from "unified";
import rehypeParse from "rehype-parse";

const repoRoot = process.cwd();
const outFile = path.join(
  repoRoot,
  "nextjs-app",
  "shared",
  "components",
  "CodeBlockWindow",
  "codeBlockFixtures.ts",
);

const samples = [
  {
    id: "tsx",
    language: "tsx",
    code: `type Props = {\n  label: string;\n};\n\nexport function DemoButton({ label }: Props) {\n  return (\n    <button type=\"button\" aria-label={label}>\n      {label}\n    </button>\n  );\n}`,
  },
  {
    id: "bash",
    language: "bash",
    code: `curl -X POST https://api.digitaltableteur.com/v1/send \\\n+  -H \"Authorization: Bearer $TOKEN\" \\\n+  -H \"Content-Type: application/json\" \\\n+  -d '{\"name\":\"Petri\",\"message\":\"Hello\"}'`,
  },
  {
    id: "json",
    language: "json",
    code: `{"service":"digitaltableteur","mode":"active","regions":["eu","us"]}`,
  },
  {
    id: "longLine",
    language: "ts",
    code: "const longLine = 'This is an intentionally long line to verify horizontal scrolling within the code window without wrapping.';",
  },
];

// Light uses github-light-high-contrast (not plain github-light): the standard
// github-light palette ships tokens like #E36209 that are only ~3.48:1 on the
// white code surface, below WCAG AA. The high-contrast variant keeps the same
// GitHub look while meeting 4.5:1.
const themes = {
  light: "github-light-high-contrast",
  dark: "github-dark",
  hcw: "github-light-high-contrast",
  hcb: "github-dark-high-contrast",
};

const toJson = (node) => {
  if (!node) return null;
  if (node.type === "text") {
    return node.value;
  }
  if (node.type !== "element") {
    return null;
  }

  const properties = { ...(node.properties ?? {}) };
  if (Array.isArray(properties.className)) {
    const classList = [...properties.className];
    const lineIndex = classList.indexOf("line");
    if (lineIndex >= 0) {
      classList.splice(lineIndex, 1);
      properties["data-line"] = "";
    }
    properties.className = classList.length > 0 ? classList : undefined;
  }

  return {
    type: "element",
    tagName: node.tagName,
    properties,
    children: (node.children ?? []).map(toJson).filter(Boolean),
  };
};

async function isUpToDate() {
  if (process.env.FORCE_CODEBLOCK_FIXTURES === "1") return false;
  try {
    const [outStat, scriptStat] = await Promise.all([
      fs.stat(outFile),
      fs.stat(path.join(repoRoot, "scripts/generate-codeblock-fixtures.mjs")),
    ]);
    return outStat.mtimeMs >= scriptStat.mtimeMs;
  } catch {
    return false;
  }
}

async function main() {
  if (await isUpToDate()) {
    console.log(
      `Skipping code block fixtures (up to date): ${path.relative(repoRoot, outFile)}`,
    );
    return;
  }

  const highlighter = await getSingletonHighlighter({
    themes: Object.values(themes),
    langs: ["plaintext"],
  });

  const parser = unified().use(rehypeParse, { fragment: true });
  const fixtures = {};

  for (const sample of samples) {
    try {
      await highlighter.loadLanguage(sample.language);
    } catch {
      await highlighter.loadLanguage("plaintext");
    }

    const html = highlighter.codeToHtml(sample.code, {
      lang: sample.language,
      themes,
      defaultColor: false,
    });

    const tree = parser.parse(html);
    const preNode = tree.children?.find((child) => child.tagName === "pre");
    if (!preNode) {
      throw new Error(`No <pre> node generated for ${sample.id}.`);
    }

    if (preNode.properties) {
      preNode.properties.style = undefined;
    }

    fixtures[sample.id] = {
      language: sample.language,
      code: sample.code,
      pre: toJson(preNode),
    };
  }

  const content = `// AUTO-GENERATED by scripts/generate-codeblock-fixtures.mjs
// Do not edit manually.

export type CodeBlockFixtureNode =
  | string
  | {
      readonly type: "element";
      readonly tagName: string;
      readonly properties?: Readonly<Record<string, unknown>>;
      readonly children?: readonly CodeBlockFixtureNode[];
    };

export type CodeBlockFixture = {
  readonly language: string;
  readonly code: string;
  readonly pre: CodeBlockFixtureNode;
};

export const codeBlockFixtures = ${JSON.stringify(fixtures, null, 2)} as const;
`;

  await fs.mkdir(path.dirname(outFile), { recursive: true });
  await fs.writeFile(outFile, content, "utf8");
  console.log(`Generated fixtures -> ${path.relative(repoRoot, outFile)}`);
}

main().catch((error) => {
  console.error("Failed to generate code block fixtures:", error);
  process.exitCode = 1;
});
