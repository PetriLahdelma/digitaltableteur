#!/usr/bin/env node
/**
 * Generates the site changelog (/changelog) from git history: one line per
 * `feat` commit on main, newest first, linked to the commit on GitHub.
 *
 * Vercel builds from a shallow clone, so the output is committed rather than
 * generated at build time. Run `npm run generate:site-changelog` after
 * pushing features to refresh it.
 */
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

const OUT = resolve("nextjs-app/shared/data/site-changelog.generated.ts");

// Commit scopes mapped to the area shown beside each line.
const AREAS = [
  ["Design system", /^(design-system|ds|tokens|react|figma|web-components|patterns|parity|contract-spec|storybook|select|filterchip|ProjectList|CategoryFilter|sprint-button|ui|a11y|pixelloop)$/],
  ["Donny", /^(donny|chat|chat\+observability|askai)$/],
  ["Tooling", /^(bench|cli|mcp|guardrails)$/],
];
// Commits about the repo's agent tooling are not site changes.
const SKIP_SCOPES = /^(agents|ci|skills|workflow)$/;

// Public-disclosure guard (security review 2026-10-21). A line that names the
// chatbot's model, tools or sanitising, security work, CI infrastructure,
// internal tooling, billing or insurance detail hands an attacker a target
// or a social-engineering pretext, so it never reaches the public log. New
// commits that match are dropped; review the output before committing.
const SKIP_TEXT =
  /copilot|claude instructions|gpt-|\bsecurity\b|billing|invoice|insurance|trigger phrase|signature generator|\bfarm\b|sanitiz|injection|\bskills?\b|founder|\blinear\b|mcp setup|agent-browser|contact form submissions/i;

// Per-commit decisions from the same review: null drops the line, a string
// replaces its text. Keyed by short SHA.
const OVERRIDES = {
  b22958ce1: "Sixth delivery card, Procurement Ready",
  "50ba7ba60": null, // chatbot model name
  "9d0b7b69b": "Process Genius coming-soon teaser on the work index",
  "5ce07600d": "Reliable Partner mark and a mobile quality pass",
  "0210e21fb": "Color specimen joins the clay spread",
  "213a2d198": "Editorial overhaul of the Home Remote case study",
  fcdcdf7ff: "Bottom-aligned caption rows and a tighter overview",
  a85e83b05: "New hero image for the Home Remote case study",
  "9b39f3bb6": "Per-component accessibility evidence gate",
  "73584ebae": null, // founder title
  "840a17278": null, // e-invoice details
  "3a2f00fb8": "WCAG tests and fixes inspired by a11y.ing",
  "3a5f1e8f4": "Hero spacing fix",
  "005e5d678": "Cal.com booking tabs on the contact page",
  "21a04c971": "Donny's avatar takes on the mood you ask for",
  ca399ae16: null, // chatbot capabilities
  "0364f3d2a": null, // agent tooling
  "9e99ba8d6": null, // agent tooling
  "965000edf": "Donny shows its answers as interactive cards",
  f3f898d37: "Donny's avatar expressions and a status dot fix",
  c42be1e49: "Random hero taglines",
  e66a8b7d7: null, // email signature generator
  "2dc7ab94c": null, // email signature generator
  "49badc04b": null, // security work
  "6782a6773": "Blog moves to Sanity",
  f8025191b: null, // internal tooling
  fa8c23e59: null, // internal tooling
  a95f70eed: null, // chatbot internals
  "7c567de4c": null, // contact form logging
};

function areaFor(scopes) {
  for (const [area, pattern] of AREAS) {
    if (scopes.some((scope) => pattern.test(scope))) return area;
  }
  return "Site";
}

function clean(text) {
  return text
    .replace(/\s*\(#\d+\)\s*$/, "") // PR number
    .replace(/\s+—\s+/g, ": ") // house style: no em dashes
    .replace(/—/g, ", ")
    .replace(/\s*·\s*/g, ", ") // house style: no middle dots
    .replace(/^\w/, (c) => c.toUpperCase())
    .trim();
}

const log = execFileSync(
  "git",
  ["log", "--no-merges", "--format=%H%x09%ad%x09%s", "--date=short", "HEAD"],
  { encoding: "utf8", maxBuffer: 64 * 1024 * 1024 },
);

const entries = [];
for (const line of log.split("\n")) {
  const [sha, date, subject] = line.split("\t");
  if (!subject) continue;
  const match = subject.match(/^feat(?:\(([^)]*)\))?!?\s*[:/]\s*(.+)$/);
  if (!match) continue;
  const scopes = (match[1] ?? "").split(/[,+]/).map((s) => s.trim()).filter(Boolean);
  const short = sha.slice(0, 9);
  if (short in OVERRIDES) {
    if (OVERRIDES[short] === null) continue;
    entries.push({ date, sha: short, area: areaFor(scopes), text: OVERRIDES[short] });
    continue;
  }
  if (scopes.some((scope) => SKIP_SCOPES.test(scope)) || SKIP_TEXT.test(match[2])) continue;
  entries.push({ date, sha: short, area: areaFor(scopes), text: clean(match[2]) });
}

const body = `// Generated by scripts/generate-site-changelog.mjs from git history. Do not edit.
// Regenerate with \`npm run generate:site-changelog\`.

export interface SiteChangelogEntry {
  /** "YYYY-MM-DD", the commit date. */
  date: string;
  /** Short commit SHA; the line links to the commit on GitHub. */
  sha: string;
  area: "Site" | "Design system" | "Donny" | "Tooling";
  text: string;
}

export const SITE_CHANGELOG: SiteChangelogEntry[] = ${JSON.stringify(entries, null, 2)};
`;

writeFileSync(OUT, body);
console.log(`site changelog: ${entries.length} entries → ${OUT}`);
