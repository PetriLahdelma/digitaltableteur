#!/usr/bin/env node
/**
 * Renders the brand mark for intake emails: `node scripts/intake-mail-logo.mjs`.
 *
 * Email clients do not show SVG, and intake mail never loads remote images,
 * so the mark travels inside each message as an inline PNG. This takes the
 * geometry unchanged from public/dt-marker.svg and draws it the way the Logo
 * component's `background` option does on light themes (--logo-background
 * circle, --logo-color mark), which reads on light and dark mail clients
 * alike. Writes app/lib/intake/service/mail-logo.ts; run again if the mark
 * changes.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import sharp from "sharp";

const root = process.cwd();
const marker = readFileSync(join(root, "public/dt-marker.svg"), "utf8");
const tokens = readFileSync(join(root, "nextjs-app/shared/styles/variables.css"), "utf8");

const token = (name) => {
  const match = tokens.match(new RegExp(`${name}:\\s*(#[0-9a-fA-F]{3,8})`));
  if (!match) throw new Error(`Token ${name} not found`);
  return match[1];
};
const background = token("--logo-background");
const color = token("--logo-color");

const group = marker.match(/<g clip-path="[^"]*">([\s\S]*?)<\/g>/);
if (!group) throw new Error("Mark geometry not found in public/dt-marker.svg");
const shapes = group[1].replace(/fill="#[0-9a-fA-F]+"/g, `fill="${color}"`);

// Same padded square viewBox and circle as Logo.tsx in background mode.
const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="637" height="637" viewBox="-121 -157 637 637">
<circle cx="197.5" cy="161.5" r="318.5" fill="${background}"/>
${shapes}
</svg>`;

// 32 px in the email, drawn at 3x for high-density screens.
const SIZE = 96;
const png = await sharp(Buffer.from(svg)).resize(SIZE, SIZE).png({ compressionLevel: 9 }).toBuffer();

const out = join(root, "app/lib/intake/service/mail-logo.ts");
writeFileSync(
  out,
  `// Generated by scripts/intake-mail-logo.mjs from public/dt-marker.svg. Do not edit.

/** The brand mark as an inline PNG for intake emails (shown at 32 px). */
export const MAIL_LOGO = {
  contentId: "dt-mark",
  filename: "digitaltableteur.png",
  contentType: "image/png",
  base64: "${png.toString("base64")}",
} as const;
`,
);
console.log(`Wrote ${out} (${png.length} bytes)`);
