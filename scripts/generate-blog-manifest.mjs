#!/usr/bin/env node
import { promises as fs } from "fs";
import path from "path";

const repoRoot = process.cwd();
const postsDir = path.join(repoRoot, "content", "posts");
const outFile = path.join(
  repoRoot,
  "nextjs-app",
  "shared",
  "data",
  "blogManifest.ts",
);

async function main() {
  try {
    const files = await fs.readdir(postsDir);
    const mdxFiles = files.filter(
      (f) => f.endsWith(".mdx") || f.endsWith(".md"),
    );

    mdxFiles.sort();

    const importLines = [];
    const entryLines = [];

    mdxFiles.forEach((file, idx) => {
      const importName = `Post${idx}`;
      const frontmatterImportName = `${importName}Frontmatter`;
      const relImport = path
        .join("../../../content/posts", file)
        .replace(/\\/g, "/");
      importLines.push(
        `import ${importName}, { frontmatter as ${frontmatterImportName} } from "${relImport}"`,
      );
      const slug = file.replace(/\.mdx?$/, "");
      entryLines.push(
        `  { slug: "${slug}", Component: ${importName} as unknown as import("react").ComponentType, frontmatter: ${frontmatterImportName} }`,
      );
    });

    const content = `// AUTO-GENERATED by scripts/generate-blog-manifest.mjs
// Do not edit manually.
${importLines.join("\n")}\n\nexport type BlogManifestEntry = {
  slug: string;
  Component: import("react").ComponentType;
  frontmatter?: {
    title?: string;
    excerpt?: string;
    readTime?: string;
    publishedAt?: string;
    seoTitle?: string;
    seoDescription?: string;
    legacyUrl?: string;
    authorName?: string;
    authorSlug?: string;
    mainImageUrl?: string;
    mainImageAlt?: string;
    mainImageCaption?: string;
  };
};

export const blogManifest: BlogManifestEntry[] = [
${entryLines.join(",\n")}
];
`;

    await fs.writeFile(outFile, content, "utf8");
    console.log(
      `Generated manifest with ${mdxFiles.length} posts -> ${path.relative(repoRoot, outFile)}`,
    );
  } catch (err) {
    console.error("Failed to generate blog manifest:", err);
    // Write an empty manifest to keep builds working
    const fallback = `export const blogManifest = [] as const;`;
    await fs.writeFile(outFile, fallback, "utf8");
    process.exitCode = 0;
  }
}

main();
