#!/usr/bin/env node
// Writes the MDX body of every post listed in app/blog/postMetadata.ts into
// app/blog/postSources.generated.ts, so the Markdown routes and llms-full.txt
// convert posts without reading the file system at runtime (a runtime read
// made the function tracer bundle most of the repository).
import { promises as fs } from "fs";
import path from "path";

const repoRoot = process.cwd();
const sourceDirs = ["content/posts", "content/drafts"].map((dir) => path.join(repoRoot, dir));
const metadataFile = path.join(repoRoot, "app", "blog", "postMetadata.ts");
const outFile = path.join(repoRoot, "app", "blog", "postSources.generated.ts");

async function listMdx(dir) {
  let entries = [];
  try {
    entries = await fs.readdir(dir, { withFileTypes: true });
  } catch {
    return [];
  }
  const nested = await Promise.all(
    entries.map((entry) => {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) return listMdx(full);
      return entry.name.endsWith(".mdx") ? [full] : [];
    }),
  );
  return nested.flat();
}

const metadata = await fs.readFile(metadataFile, "utf8");
const listed = new Set([...metadata.matchAll(/^\s*slug: "([^"]+)",$/gm)].map((m) => m[1]));

const sources = {};
for (const dir of sourceDirs) {
  for (const file of (await listMdx(dir)).sort()) {
    const raw = (await fs.readFile(file, "utf8")).replace(/\r\n?/g, "\n");
    const frontmatter = raw.match(/^---\n([\s\S]*?)\n---\n/);
    const slug = frontmatter?.[1].match(/^slug:\s*"?([^"\n]+)"?\s*$/m)?.[1];
    if (!slug || !listed.has(slug) || slug in sources) continue;
    sources[slug] = raw.slice(frontmatter[0].length);
  }
}

const body = Object.keys(sources)
  .sort()
  .map((slug) => `  ${JSON.stringify(slug)}: ${JSON.stringify(sources[slug])},`)
  .join("\n");
const content = `// AUTO-GENERATED by scripts/generate-post-sources.mjs. Do not edit manually.
// MDX bodies (frontmatter removed) of the posts listed in postMetadata.ts.

export const POST_SOURCES: Record<string, string> = {
${body}
};
`;
await fs.writeFile(outFile, content, "utf8");
console.log(`Wrote ${Object.keys(sources).length} post sources to ${path.relative(repoRoot, outFile)}`);
